-- Индексы под фоновые задачи PR 2 (PAYMENT_DESIGN.md §6): сверка и повтор возвратов.
--
-- Обе задачи раз в несколько секунд ищут платежи в одном конкретном статусе. Без индекса
-- это последовательный скан ВСЕЙ таблицы payments, которая только растёт (платежи не
-- удаляются), — при том что искомых строк единицы.
--
-- Частичные индексы (WHERE status = ...): в индекс попадают только строки в «рабочем»
-- статусе. Подавляющее большинство платежей терминальные (PAID, FAILED, REFUNDED) и в эти
-- индексы не входят — индекс остаётся крошечным. Запрос использует частичный индекс, только
-- если его WHERE содержит то же условие на status, поэтому задачи фильтруют по литералу
-- статуса (см. PaymentRepository).

-- Сверка: PENDING с истёкшим сроком счёта, по возрастанию expires_at.
CREATE INDEX idx_payments_pending_expires ON payments (expires_at) WHERE status = 'PENDING';

-- Повтор возвратов: REFUND_PENDING, давно не менявшиеся (updated_at).
CREATE INDEX idx_payments_refund_pending ON payments (updated_at) WHERE status = 'REFUND_PENDING';
